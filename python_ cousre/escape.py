print("Hey how are you\nI am good") # \n is used to print in new line
print("This is a tab\tcharacter") # \t is used to print in tab space
print("This is a backslash\\character") # \\ is used to print a backslash
print("This is a quote\"character") # \" is used to print a double quote
print("This is a single quote\'character") # \' is used to print a single quote